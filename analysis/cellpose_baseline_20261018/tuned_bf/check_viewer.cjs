const {chromium}=require('C:/Users/spraman/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const path=require('path');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 const page=await browser.newPage({viewport:{width:900,height:1200}}),errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('file:///'+path.resolve(__dirname,'viewer_preview.html').replaceAll('\\','/'));
 const frame=page.frameLocator('iframe');
 await frame.locator('#cp-status').filter({hasText:'D5_0004'}).waitFor();
 await frame.locator('#cp-canvas').evaluate(async c=>{await new Promise(r=>setTimeout(r,300));if(!c.getContext('2d').getImageData(200,200,1,1).data[3])throw Error('Image not drawn');});
 const before=await frame.locator('#cp-canvas').evaluate(c=>c.toDataURL());
 await frame.locator('#cp-blend').fill('100');
 const after=await frame.locator('#cp-canvas').evaluate(c=>c.toDataURL());
 if(before===after)throw Error('Fluorescence control failed');
 await frame.locator('#cp-variant').selectOption('default');
 if(!(await frame.locator('#cp-status').textContent()).includes('Default:'))throw Error('Settings switch failed');
 await frame.locator('#cp-field').selectOption('4');
 if(!(await frame.locator('#cp-status').textContent()).includes('Weak GFP'))throw Error('D9 warning missing');
 await frame.locator('#cp-field').selectOption('0');await frame.locator('#cp-variant').selectOption('selected');
 await frame.locator('#cp-blend').fill('0');await frame.locator('#cp-zoom').selectOption('2');
 await frame.locator('#cp-canvas').click({position:{x:320,y:250}});
 await frame.locator('#cp-zoom').selectOption('1');
 await page.screenshot({path:path.resolve(__dirname,'viewer_desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:1000});
 await page.screenshot({path:path.resolve(__dirname,'viewer_mobile.png'),fullPage:true});
 const overflow=await frame.locator('#cellpose-bf-review').evaluate(r=>document.documentElement.scrollWidth>document.documentElement.clientWidth+2);
 if(overflow)throw Error('Horizontal overflow');
 if(errors.length)throw Error(errors.join('\n'));
 console.log('Viewer: image rendering, blend, settings, field switching, zoom and narrow layout passed');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
